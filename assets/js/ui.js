let toastRoot;
export function toast(msg, kind = "") {
  if (!toastRoot) {
    toastRoot = h("div", { id: "toast-root", role: "status", "aria-live": "polite" });
    document.body.append(toastRoot);
  }
  const el = h("div", { class: "toast " + kind }, msg);
  toastRoot.append(el);
  setTimeout(() => {
    el.style.transition = "opacity .4s, transform .4s";
    el.style.opacity = "0";
    el.style.transform = "translateY(6px)";
    setTimeout(() => el.remove(), 420);
  }, 3400);
  return el;
}

/**  promise 化的确认框 */
export function confirmDialog(message, { title = "确认" } = {}) {
  return new Promise((resolve) => {
    const dlg = h("dialog", { class: "dlg" },
      h("h2", {}, title),
      h("p", { style: "font-size:13px;line-height:1.9;margin-bottom:20px" }, message),
      h("div", { style: "display:flex;gap:10px;justify-content:flex-end" },
        h("button", { class: "btn-ghost", onclick: () => { dlg.close(); resolve(false); } }, "取消"),
        h("button", { class: "btn-primary", onclick: () => { dlg.close(); resolve(true); } }, "确定")
      )
    );
    dlg.addEventListener("close", () => { resolve(false); dlg.remove(); }, { once: true });
    document.body.append(dlg);
    dlg.showModal();
  });
}

